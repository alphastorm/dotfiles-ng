import { execFile } from "node:child_process";
import { existsSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { ExtensionAPI } from "@oh-my-pi/pi-coding-agent";
import {
	isJsonObject,
	readJson,
	writeJsonOnce,
} from "../skills/critical-review/lrhe/json-object.ts";

const REVIEWER_MARKER = "CRITICAL_REVIEWER_READ_ONLY_V1";
const FABLE_REVIEWER_MARKER = "FABLE_ARCHITECTURE_REVIEWER_READ_ONLY_V2";
const INLINE_ISOLATED_MARKER = "CRITICAL_REVIEWER_INLINE_ISOLATED_V1";
const ISOLATED_TOOLS: Record<string, true> = { yield: true };
const READ_ONLY_TOOLS: Record<string, true> = {
	read: true,
	grep: true,
	glob: true,
	lsp: true,
	ast_grep: true,
	yield: true,
};

const TASK_TOOL = "task";
const BLOCK_PREFIX = "critical-review dispatch";

/** Every reviewer seat runs a `review-*` agent, so a Task item naming one is a protected item. */
export const REVIEWER_AGENT_PREFIX = "review-";
/** First line of the shared machine marker the lead passes as the batch `context`. */
export const DISPATCH_MARKER_HEADER = "CRITICAL_REVIEW_DISPATCH_V1";
/** First token of every resolver-generated reviewer task body. */
export const RESOLVER_RECEIPT_HEADER = "CRITICAL_REVIEW_RESOLVER_RECEIPT_V1";

// The entire marker, not a prefix: `$` in a non-multiline JS pattern only matches end of input, so a
// trailing newline, leading whitespace, or any surrounding prose is a mismatch and fails closed.
const MARKER_PATTERN =
	/^CRITICAL_REVIEW_DISPATCH_V1\nenvelope_path=(\/[^\n]+)\nenvelope_sha256=([0-9a-f]{64})$/u;

/**
 * Fixed sibling of this extension, resolved from this module's own realpath, so no caller can point
 * the gate at a different verifier. The skill half and this file are deployed side by side, which
 * makes the relative path correct both in the dotfiles checkout and under `~/.omp/agent`.
 */
export const VERIFIER_SCRIPT = fileURLToPath(
	new URL("../skills/critical-review/lrhe/review_dispatch.py", import.meta.url),
);
/** The skill's own interpreter, used when present because the verifier needs the skill's PyYAML. */
export const VERIFIER_PYTHON = fileURLToPath(
	new URL("../skills/critical-review/lrhe/.venv/bin/python", import.meta.url),
);
export const VERIFIER_TIMEOUT_MS = 30_000;
const VERIFIER_MAX_OUTPUT_BYTES = 4 * 1024 * 1024;
const VERIFIER_REASON_LIMIT = 500;

export interface DispatchMarker {
	envelopePath: string;
	envelopeSha256: string;
}

export interface CanonicalTaskInput {
	context: string;
	/** The task tool's required intent field; generated by the resolver, compared byte for byte whenever the delivered call still carries it. */
	i: string;
	tasks: Record<string, unknown>[];
}

/**
 * The input a tool_call hook receives. OMP owns the intent field: with `tools.intentTracing` on
 * (observed in omp 18.5.1), its agent loop and eval bridge strip `i` from a call whose tool schema
 * does not declare it, before any hook runs. The verifier still emits `i` because the call must
 * carry it on the wire, so the gate compares the canonical in the shape the harness delivered.
 */
export type DeliveredTaskInput = CanonicalTaskInput | Omit<CanonicalTaskInput, "i">;

/** Resolves the verifier's stdout on a clean exit; rejects on any other outcome. */
export type VerifyTask = (marker: DispatchMarker) => Promise<string>;

/** A verified protected call carries its delivered input, each item's canonical seat, and the full batch. */
export type DispatchDecision =
	| { block: true; reason: string }
	| { input: DeliveredTaskInput; seats: number[]; canonical: CanonicalTaskInput }
	| undefined;

/** Schema of the record the gate writes beside an envelope for each of its settled Task calls. */
export const TASK_ATTEMPT_SCHEMA = "critical-review-task-attempt-v1";

/** One canonical seat's budget: it runs once and, after failing, at most once more. */
interface SeatState {
	attempts: number;
	failed: boolean;
}

interface EnvelopeState {
	envelopePath: string;
	canonical: CanonicalTaskInput;
	seats: SeatState[];
	settledCalls: number;
	activeCallId: string | undefined;
}

function blocked(reason: string): { block: true; reason: string } {
	return { block: true, reason: `${BLOCK_PREFIX}: ${reason}` };
}

/** Structural JSON equality: array order matters, object key order does not, extra keys never do. */
export function deepEqual(left: unknown, right: unknown): boolean {
	if (left === right) return true;
	if (Array.isArray(left) || Array.isArray(right)) {
		if (
			!Array.isArray(left) ||
			!Array.isArray(right) ||
			left.length !== right.length
		)
			return false;
		return left.every((value, index) => deepEqual(value, right[index]));
	}
	if (!isJsonObject(left) || !isJsonObject(right)) return false;
	const keys = Object.keys(left);
	if (keys.length !== Object.keys(right).length) return false;
	return keys.every(
		(key) => Object.hasOwn(right, key) && deepEqual(left[key], right[key]),
	);
}

export function isReviewerItem(item: unknown): item is Record<string, unknown> {
	return (
		isJsonObject(item) &&
		typeof item.agent === "string" &&
		item.agent.startsWith(REVIEWER_AGENT_PREFIX)
	);
}

// The resolver emits each seat as exactly `{agent, task}`; a stray `name`, `effort`, or output
// schema means the payload did not come from the resolver and must not reach the task tool.
function isCanonicalTaskItem(item: unknown): item is Record<string, unknown> {
	if (!isReviewerItem(item)) return false;
	const keys = Object.keys(item).sort();
	if (keys.length !== 2 || keys[0] !== "agent" || keys[1] !== "task")
		return false;
	return (
		typeof item.task === "string" &&
		item.task.startsWith(RESOLVER_RECEIPT_HEADER)
	);
}

export function parseDispatchMarker(context: unknown): DispatchMarker | null {
	if (typeof context !== "string") return null;
	const match = MARKER_PATTERN.exec(context);
	const envelopePath = match?.[1];
	const envelopeSha256 = match?.[2];
	if (!envelopePath || !envelopeSha256) return null;
	return { envelopePath, envelopeSha256 };
}


/**
 * Accepts only the exact canonical batch Task shape `{context, i, tasks}`.
 * A canary or targeted refuter is a one-item batch; focused reviews and
 * councils use the same shape without creating a second reviewer convention.
 */
export function parseVerifierOutput(
	stdout: unknown,
): CanonicalTaskInput | null {
	if (typeof stdout !== "string") return null;
	let parsed: unknown;
	try {
		parsed = JSON.parse(stdout);
	} catch {
		return null;
	}
	if (!isJsonObject(parsed)) return null;
	const outerKeys = Object.keys(parsed);
	if (outerKeys.length !== 1 || outerKeys[0] !== "task_input") return null;
	const taskInput = parsed.task_input;
	if (!isJsonObject(taskInput)) return null;
	const innerKeys = Object.keys(taskInput).sort();
	if (
		innerKeys.length !== 3 ||
		innerKeys[0] !== "context" ||
		innerKeys[1] !== "i" ||
		innerKeys[2] !== "tasks"
	)
		return null;
	const { context, i, tasks } = taskInput;
	if (typeof context !== "string" || !parseDispatchMarker(context)) return null;
	if (typeof i !== "string" || i.trim().length === 0) return null;
	if (!Array.isArray(tasks) || tasks.length < 1) return null;
	if (!tasks.every(isCanonicalTaskItem)) return null;
	return { context, i, tasks };
}

function verifierFailureReason(error: unknown, stderr?: string): string {
	const refusal = (stderr ?? "")
		.trim()
		.split("\n")[0]
		?.slice(0, VERIFIER_REASON_LIMIT);
	if (!isJsonObject(error))
		return `verifier could not be run: ${String(error)}`;
	if (
		error.killed === true ||
		(typeof error.signal === "string" && error.signal.length > 0)
	) {
		return `verifier exceeded its ${VERIFIER_TIMEOUT_MS}ms budget`;
	}
	const message =
		typeof error.message === "string" ? error.message : String(error);
	const detail = refusal || message.slice(0, VERIFIER_REASON_LIMIT);
	if (typeof error.code === "number")
		return `verifier exited with code ${error.code}: ${detail}`;
	return `verifier could not be run: ${detail}`;
}

/**
 * Runs the fixed sibling verifier with an argv array — never a shell — under a hard timeout that
 * SIGKILLs the child rather than leaving the gate waiting on it. The verifier reaches PyYAML through
 * the skill's qualification module, which only re-execs into the virtualenv as `__main__`, so the
 * skill's own interpreter is preferred over a bare `python3` that may not have it.
 */
export const verifyTaskViaSkill: VerifyTask = (marker) =>
	new Promise<string>((resolve, reject) => {
		execFile(
			existsSync(VERIFIER_PYTHON) ? VERIFIER_PYTHON : "python3",
			[
				VERIFIER_SCRIPT,
				"verify-task",
				"--envelope",
				marker.envelopePath,
				"--sha256",
				marker.envelopeSha256,
			],
			{
				encoding: "utf8",
				killSignal: "SIGKILL",
				maxBuffer: VERIFIER_MAX_OUTPUT_BYTES,
				shell: false,
				timeout: VERIFIER_TIMEOUT_MS,
				windowsHide: true,
			},
			(error, stdout, stderr) => {
				if (error) reject(new Error(verifierFailureReason(error, stderr)));
				else resolve(stdout);
			},
		);
	});

/**
 * Gate for parent `task` calls. Reviewer batches must contain only reviewer
 * items and carry the exact context marker. A single reviewer uses the same
 * batch shape with one item. Calls with no reviewer pass. A verified call may
 * carry any unchanged, order-preserving subset of the canonical seats; which
 * seats an envelope may still run is the lifecycle's decision, not this one.
 */
export async function evaluateTaskDispatch(
	rawInput: unknown,
	verify: VerifyTask = verifyTaskViaSkill,
): Promise<DispatchDecision> {
	if (!isJsonObject(rawInput)) return undefined;
	const tasks = rawInput.tasks;
	if (!Array.isArray(tasks)) {
		if (!isReviewerItem(rawInput)) return undefined;
		return blocked(
			"reviewers must use the verifier-generated batch Task shape.",
		);
	}
	if (!tasks.some(isReviewerItem)) return undefined;
	if (!tasks.every(isReviewerItem)) {
		return blocked(
			`a batch containing a ${REVIEWER_AGENT_PREFIX}* agent must contain only reviewer items.`,
		);
	}
	const marker = parseDispatchMarker(rawInput.context);
	if (!marker) {
		return blocked(
			`the task context is not an exact ${DISPATCH_MARKER_HEADER} marker; use review_dispatch.py prepare, which binds the repository's committed REVIEW.md when present.`,
		);
	}

	let stdout: string;
	try {
		stdout = await verify(marker);
	} catch (error) {
		return blocked(
			error instanceof Error ? error.message : verifierFailureReason(error),
		);
	}
	const canonical = parseVerifierOutput(stdout);
	if (!canonical) {
		return blocked("the verifier did not emit a strict task_input object.");
	}
	const seats: number[] = [];
	let next = 0;
	for (const item of tasks) {
		while (next < canonical.tasks.length && !deepEqual(item, canonical.tasks[next])) next += 1;
		if (next === canonical.tasks.length) {
			return blocked(
				"this call does not match the verifier-approved canonical dispatch.",
			);
		}
		seats.push(next);
		next += 1;
	}
	const selected: CanonicalTaskInput = {
		...canonical,
		tasks: canonical.tasks.filter((_, seat) => seats.includes(seat)),
	};
	const { i: _intent, ...withoutIntent } = selected;
	const delivered: DeliveredTaskInput = Object.hasOwn(rawInput, "i") ? selected : withoutIntent;
	if (!deepEqual(rawInput, delivered)) {
		return blocked(
			"this call does not match the verifier-approved canonical dispatch.",
		);
	}
	return { input: delivered, seats, canonical };
}

/** `<envelope-stem>.attempt-<n>.json`: the record of an envelope's n-th settled Task call. */
export function attemptPath(envelopePath: string, attempt: number): string {
	return join(dirname(envelopePath), `${basename(envelopePath, ".json")}.attempt-${attempt}.json`);
}

/**
 * Rebuilds an envelope's per-seat budget from the attempt records beside it, so a restarted
 * process can retry a failed seat alone and never reruns a seat that completed.
 */
async function loadEnvelopeState(
	marker: DispatchMarker,
	canonical: CanonicalTaskInput,
): Promise<EnvelopeState> {
	const seats: SeatState[] = canonical.tasks.map(() => ({ attempts: 0, failed: false }));
	let settledCalls = 0;
	for (;;) {
		const path = attemptPath(marker.envelopePath, settledCalls + 1);
		let record: Record<string, unknown>;
		try {
			record = await readJson(path);
		} catch (error) {
			if (isJsonObject(error) && error.code === "ENOENT") break;
			throw error;
		}
		if (
			record.schema !== TASK_ATTEMPT_SCHEMA ||
			record.envelopeSha256 !== marker.envelopeSha256 ||
			!Array.isArray(record.seats)
		) {
			throw new Error(`${path} is not an attempt record of this envelope`);
		}
		for (const entry of record.seats) {
			if (!isJsonObject(entry) || typeof entry.seat !== "number" || typeof entry.failed !== "boolean") {
				throw new Error(`${path} has a malformed seat outcome`);
			}
			const seat = seats[entry.seat];
			if (!seat) throw new Error(`${path} records a seat this envelope does not have`);
			seat.attempts += 1;
			seat.failed = entry.failed;
		}
		settledCalls += 1;
	}
	return { envelopePath: marker.envelopePath, canonical, seats, settledCalls, activeCallId: undefined };
}

/**
 * Enforces the reviewer boundary even when OMP injects coordination tools into subagents, and gates
 * the parent side so a reviewer seat can only be spawned from a verified dispatch envelope. The
 * loader passes only `pi`; `verify` exists so tests can drive the gate without spawning the skill.
 */
export default function criticalReviewPolicy(
	pi: ExtensionAPI,
	verify: VerifyTask = verifyTaskViaSkill,
): void {
	// Keyed by envelope digest, so a path alias shares one budget; calls racing on an envelope's
	// first sight share one load, and so one state.
	const envelopes = new Map<string, Promise<EnvelopeState>>();
	const activeCalls = new Map<
		string,
		{ envelope: EnvelopeState; envelopeSha256: string; seats: number[] }
	>();

	pi.on("tool_call", async (event, ctx) => {
		const prompt = ctx.getSystemPrompt();
		const isolated = prompt.some((part) =>
			part.includes(INLINE_ISOLATED_MARKER),
		);
		const isCriticalReviewer =
			isolated ||
			prompt.some(
				(part) =>
					part.includes(REVIEWER_MARKER) ||
					part.includes(FABLE_REVIEWER_MARKER),
			);
		if (isCriticalReviewer) {
			const allowedTools = isolated ? ISOLATED_TOOLS : READ_ONLY_TOOLS;
			if (allowedTools[event.toolName]) return;
			return {
				block: true,
				reason: `Critical reviewers are read-only and isolated; ${event.toolName} is not permitted.`,
			};
		}

		if (event.toolName !== TASK_TOOL) return;
		const decision = await evaluateTaskDispatch(event.input, verify);
		if (!decision || "block" in decision) return decision;
		const marker = parseDispatchMarker(decision.input.context);
		if (!marker) return blocked("the verified dispatch marker disappeared.");
		let loading = envelopes.get(marker.envelopeSha256);
		if (!loading) {
			loading = loadEnvelopeState(marker, decision.canonical);
			envelopes.set(marker.envelopeSha256, loading);
		}
		let envelope: EnvelopeState;
		try {
			envelope = await loading;
		} catch (error) {
			envelopes.delete(marker.envelopeSha256);
			return blocked(
				`this envelope's attempt history is unreadable (${error instanceof Error ? error.message : String(error)}); repair or move that record aside before redispatching.`,
			);
		}
		// No await from here to the reservation, so two racing calls cannot both pass these checks.
		if (envelope.activeCallId) {
			return blocked(
				"this envelope already has an unresolved Task call; an outer eval background acknowledgement is not that call's result. Wait for the original call to settle instead of redispatching. A call refused before any reviewer started never settles in this process: restart OMP and continue from the envelope's attempt records.",
			);
		}
		const firstDispatch = envelope.seats.every((seat) => seat.attempts === 0);
		if (firstDispatch && decision.seats.length !== envelope.seats.length) {
			return blocked(
				"the first dispatch of an envelope must be its complete resolver batch.",
			);
		}
		const refused = firstDispatch
			? []
			: decision.seats.filter(
					(seat) => !envelope.seats[seat].failed || envelope.seats[seat].attempts !== 1,
				);
		if (refused.length > 0) {
			return blocked(
				`only a failed seat may run again, and only once, so ${refused.map((seat) => envelope.canonical.tasks[seat].agent).join(", ")} cannot. Submit the latest attempt record's retryTaskInput unchanged.`,
			);
		}
		for (const seat of decision.seats) envelope.seats[seat].attempts += 1;
		envelope.activeCallId = event.toolCallId;
		activeCalls.set(event.toolCallId, {
			envelope,
			envelopeSha256: marker.envelopeSha256,
			seats: decision.seats,
		});
		return { input: decision.input };
	});

	pi.on("tool_result", async (event) => {
		if (event.toolName !== TASK_TOOL) return;
		const call = activeCalls.get(event.toolCallId);
		if (!call) return;
		activeCalls.delete(event.toolCallId);
		const { envelope, envelopeSha256, seats } = call;
		envelope.activeCallId = undefined;
		// Each native row carries its position in this call. The top-level error flag reflects only
		// thrown spawns, so a seat that exited non-zero, aborted, or returned nothing is read here.
		const results =
			isJsonObject(event.details) && Array.isArray(event.details.results)
				? event.details.results
				: [];
		const outcomes = seats.map((seat, position) => {
			const row = results.find(
				(result) => isJsonObject(result) && result.index === position,
			);
			const exitCode = isJsonObject(row) && typeof row.exitCode === "number" ? row.exitCode : null;
			const aborted = isJsonObject(row) && row.aborted === true;
			const failed = exitCode !== 0 || aborted;
			envelope.seats[seat].failed = failed;
			return {
				seat,
				agent: envelope.canonical.tasks[seat].agent,
				failed,
				exitCode,
				aborted,
				error: isJsonObject(row) && typeof row.error === "string" ? row.error : null,
			};
		});
		envelope.settledCalls += 1;
		const attempt = envelope.settledCalls;
		const retrySeats = envelope.seats.flatMap((state, seat) =>
			state.failed && state.attempts === 1 ? [seat] : [],
		);
		const retryTaskInput =
			retrySeats.length === 0
				? null
				: {
						...envelope.canonical,
						tasks: envelope.canonical.tasks.filter((_, seat) => retrySeats.includes(seat)),
					};
		const path = attemptPath(envelope.envelopePath, attempt);
		let recorded = false;
		let note: string;
		try {
			recorded = await writeJsonOnce(path, {
				schema: TASK_ATTEMPT_SCHEMA,
				envelopePath: envelope.envelopePath,
				envelopeSha256,
				attempt,
				toolCallId: event.toolCallId,
				settledAt: new Date().toISOString(),
				seats: outcomes,
				retryTaskInput,
				result: { isError: event.isError, content: event.content, details: event.details },
			});
			note = recorded
				? `attempt ${attempt} is recorded in ${path}`
				: `attempt ${attempt} was not recorded: ${path} already exists`;
		} catch (error) {
			note = `attempt ${attempt} could not be recorded (${error instanceof Error ? error.message : String(error)})`;
		}
		const seatSummary = outcomes
			.map(({ agent, failed, exitCode }) =>
				failed
					? `${agent} failed${exitCode === null ? "" : ` (exit ${exitCode})`}`
					: `${agent} completed`,
			)
			.join("; ");
		const retry =
			retryTaskInput === null
				? ""
				: ` One retry is open for ${retryTaskInput.tasks.map((task) => task.agent).join(", ")}: ${recorded ? "submit that record's retryTaskInput unchanged" : "submit the prepared task_input reduced to those items, unchanged and in order"}.`;
		return {
			content: [
				...event.content,
				{ type: "text" as const, text: `${BLOCK_PREFIX}: ${note}. ${seatSummary}.${retry}` },
			],
		};
	});

	pi.on("session_shutdown", () => {
		envelopes.clear();
		activeCalls.clear();
	});
}
